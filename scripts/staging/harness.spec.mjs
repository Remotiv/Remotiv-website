/**
 * The independently generated expected answer, loaded once.
 *
 * Refused rather than defaulted if it is absent or thin. An empty expected set
 * makes every comparison below pass against any read at all.
 */
function loadManifest() {
  let raw;
  try {
    raw = readFileSync(MANIFEST_PATH, "utf8");
  } catch {
    throw new Error(
      `no manifest at ${MANIFEST_PATH}. It is written by seed.mjs ONLY after the seed's ` +
        `own visibility self-check passed, and it is the expected id set every assertion ` +
        `here compares against. Run the seed first.`,
    );
  }
  const m = JSON.parse(raw);
  for (const key of ["applicationIdsAll", "scopedApplicationIds", "jobIds"]) {
    if (!Array.isArray(m[key]) || m[key].length === 0) {
      throw new Error(`manifest.${key} is empty; every comparison against it would pass`);
    }
  }
  if (!m.companyId) throw new Error("manifest has no companyId");
  if (!m.scale || !Number.isInteger(m.scale.applicants) || !Array.isArray(m.notCovered)) {
    throw new Error("manifest records no scale; it predates --applicants. Re-run the seed.");
  }
  return m;
}

