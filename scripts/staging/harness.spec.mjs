const LOGIN_TIMEOUT_MS = 60_000;

/** React has attached a fiber to the node: the form's onSubmit is live. */
const isHydrated = (el) => Object.keys(el).some((k) => k.startsWith("__reactFiber$"));

/**
 * Sign in through the real form, and NAME the outcome.
 *
 * The credentials are test accounts that exist only in the staging project,
 * supplied by name from the environment and never printed. The inputs are
 * addressed by id: getByLabel(/password/i) would also match the show-password
 * button's aria-label and fail strict mode.
 *
 * The first 50-row run spent ten minutes in ten identical 60 s timeouts on the
 * dashboard URL, and the only diagnosis was a navigation log. Three things
 * the app can do after the click are now told apart, each by a mechanism the
 * app itself exposes, with no 60 s wait behind any of them:
 *
 *   - lands on /ai-dashboard: signed in;
 *   - lands on /ai-dashboard/change-password: the company row's
 *     must_change_password is true (gated layout.tsx:94), which the seed now
 *     writes false and assertAccountUsable refuses in beforeAll;
 *   - shows the form's OWN banner (LOGIN_BANNER): the server action refused,
 *     and the fixed copy says which way (classified to a key, never printed;
 *     an empty read is refused, not classified: assertions.mjs).
 *
 * The click is held until React has hydrated the form. Before that, a submit
 * is the browser's own: a reload of the login page with nothing sent, which
 * is what "navigated to /ai-dashboard/login" and nothing after it looks like.
 * And before the click, each field is read back and must equal what was set
 * (requireFilled): a fill that did not land would submit an empty form, and
 * everything after would describe that form, not the sign-in.
 */
async function signInOnce(page, account) {
  // The COMPANY login, not /login: /login is the admin form (#al-*), and it
  // pushes to /admin. The company form (#co-*) does a full document load of
  // /ai-dashboard on success. harness-wiring.test.mjs pins both ids to source.
  await page.goto(`${BASE}${LOGIN_PATH}`, { waitUntil: "domcontentloaded" });
  await expect
    .poll(() => page.locator("#co-email").evaluate(isHydrated), {
      timeout: LOGIN_TIMEOUT_MS,
      message: "the login form never hydrated; a click now would be a plain page reload",
    })
    .toBe(true);
  await page.locator("#co-email").fill(account.email);
  await page.locator("#co-password").fill(account.password);
  requireFilled("#co-email", await page.locator("#co-email").inputValue(), account.email);
  requireFilled("#co-password", await page.locator("#co-password").inputValue(), account.password);
  await page.getByRole("button", { name: "Sign In" }).click();

  const outcome = await new Promise((resolve) => {
    const arm = (p, label) =>
      p.then(
        () => resolve(label),
        () => {},
      );
    const opts = { timeout: LOGIN_TIMEOUT_MS };
    arm(
      page.waitForURL((u) => u.pathname === "/ai-dashboard", opts),
      "dashboard",
    );
    arm(
      page.waitForURL((u) => u.pathname === "/ai-dashboard/change-password", opts),
      "forced",
    );
    arm(page.locator(LOGIN_BANNER).waitFor(opts), "refused");
    setTimeout(() => resolve("timeout"), LOGIN_TIMEOUT_MS + 1_000).unref();
  });
  if (outcome === "dashboard") return { outcome };
  if (outcome === "forced") {
    throw new Error(
      `the app signed ${account.emailVar} in and sent it to /ai-dashboard/change-password?forced=true: ` +
        `the fixture company's must_change_password is true (gated layout.tsx:94). The seed writes ` +
        `it false and beforeAll refuses it true; this fixture predates that. Teardown, then re-seed.`,
    );
  }
  if (outcome === "refused") {
    // Throws on an empty or unrecognised read; a key is only ever a real refusal.
    return { outcome, key: classifyLoginRefusal(await page.locator(LOGIN_BANNER).innerText()) };
  }
  return { outcome: "timeout" };
}

/**
 * Sign in, with ONE counted retry for the refusals that have been seen once
 * and gone away (the scoped account was refused as "credentials" once in
 * five form logins on 2026-10-27; the SDK path never was). The retry is
 * printed when it happens and listed under FLAKES OBSERVED at the end. A
 * second refusal fails, with the key. The forced password redirect is never
 * retried: it is a fixture fault, not a flake.
 */
async function signIn(page, account = ACCOUNTS.owner) {
  for (let attempt = 1; ; attempt += 1) {
    const r = await signInOnce(page, account);
    if (r.outcome === "dashboard") return;
    const why =
      r.outcome === "refused"
        ? `refused as ${r.key}`
        : `no outcome within ${LOGIN_TIMEOUT_MS} ms (no navigation, no banner)`;
    const retryable = r.outcome === "timeout" || RETRYABLE_REFUSALS.has(r.key);
    if (attempt < MAX_LOGIN_ATTEMPTS && retryable) {
      const note = `login: ${account.emailVar} ${why} on attempt ${attempt}; retried once`;
      flakes.push(note);
      console.log(`  FLAKE ${note}`);
      await page.waitForTimeout(r.key === "rate_limited" ? 65_000 : 3_000);
      continue;
    }
    throw new Error(
      `the login form ${why} for ${account.emailVar} on attempt ${attempt} of ${MAX_LOGIN_ATTEMPTS}. ` +
        `The SDK sign-in in beforeAll passed with the same variables; credentials/unavailable/error ` +
        `are the server action's own collapsed keys, rate_limited is the auth endpoint's per-IP limit.`,
    );
  }
}

