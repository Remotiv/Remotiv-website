"use server";
import { requireSuperAdmin } from "@/app/admin/lib/role-guards";
import {
  ERASURE_AUDIT_TABLE,
  isOperationId,
  readSweepCounts,
  SWEEP_PREVIEW_RPC,
  SWEEP_RPC,
  type SweepCounts,
  sweepCutoff,
  UNIQUE_VIOLATION,
} from "@/lib/erasure/orphan-sweep";
import { createServiceClient } from "@/lib/supabase/server";

/**
 * The orphan sweep (#72, migration 056), super admin only.
 *
 * Preview counts and writes nothing. The sweep clears message rows and
 * deletes name-bearing bells orphaned before the window, through one
 * database function that is atomic and idempotent by operation id. The id is
 * generated by the caller and passed back on a retry, because a commit can
 * land while the connection dies: the function answers a committed id from
 * its record and touches nothing again.
 *
 * Cross-company by nature: an orphan belongs to no application and the
 * sweep reads no job_applications row, so there is no tenancy to consume
 * here and nothing for a company filter to attach to.
 *
 * No raw database text reaches the caller; it goes to the server log.
 */

export type SweepPreview =
  | { ok: true; counts: SweepCounts; cutoff: string }
  | { ok: false; error: string };

export type SweepOutcome =
  | { ok: true; counts: SweepCounts; cutoff: string; committed: "now" | "earlier" }
  | {
      ok: false;
      error: string;
      /** "same-id": call again with the same operation id. "none": do not retry. */
      retry: "same-id" | "none";
    };

export async function previewOrphanSweep(): Promise<SweepPreview> {
  await requireSuperAdmin();
  const service = createServiceClient();
  const cutoff = sweepCutoff(Date.now()).toISOString();
  const { data, error } = await service.rpc(SWEEP_PREVIEW_RPC, { p_orphaned_before: cutoff });
  if (error) {
    console.error("[erasure] preview failed:", error.message);
    return { ok: false, error: "The preview could not be read." };
  }
  const counts = readSweepCounts(data);
  if (!counts) return { ok: false, error: "The preview answered in an unexpected shape." };
  return { ok: true, counts, cutoff };
}

export async function runOrphanSweep(operationId: string): Promise<SweepOutcome> {
  const ctx = await requireSuperAdmin();
  if (!isOperationId(operationId)) {
    return { ok: false, error: "A sweep needs a client-generated operation id.", retry: "none" };
  }
  const service = createServiceClient();
  const cutoff = sweepCutoff(Date.now()).toISOString();

  const { data, error } = await service.rpc(SWEEP_RPC, {
    p_operation_id: operationId,
    p_performed_by: ctx.user.id,
    p_orphaned_before: cutoff,
  });

  if (!error) {
    const counts = readSweepCounts(data);
    if (!counts) {
      return { ok: false, error: "The sweep answered in an unexpected shape.", retry: "none" };
    }
    return { ok: true, counts, cutoff, committed: "now" };
  }

  if (error.code === UNIQUE_VIOLATION) {
    /*
     * 23505 is not "already done" on its own: re-read by operation id. A row
     * means an earlier call committed and this is its answer. No row means
     * the violation was a DIFFERENT constraint, and that is a real error.
     */
    const { data: row, error: readErr } = await service
      .from(ERASURE_AUDIT_TABLE)
      .select("cleared")
      .eq("operation_id", operationId)
      .maybeSingle();
    if (readErr) {
      console.error("[erasure] record read failed after 23505:", readErr.message);
      return {
        ok: false,
        error: "The sweep may have run; its record could not be read. Retry with the same id.",
        retry: "same-id",
      };
    }
    const counts = readSweepCounts((row as { cleared?: unknown } | null)?.cleared);
    if (counts) return { ok: true, counts, cutoff, committed: "earlier" };
    console.error("[erasure] 23505 without a matching record:", error.message);
    return {
      ok: false,
      error: "The database refused the sweep's record for a reason other than a repeat.",
      retry: "none",
    };
  }

  console.error("[erasure] sweep failed:", error.message);
  return {
    ok: false,
    error: "The sweep did not run. Retry with the same operation id.",
    retry: "same-id",
  };
}
